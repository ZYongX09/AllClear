/**
 * The web Worker's bindings, typed.
 *
 * `env` comes from the `cloudflare:workers` module, which the Workers runtime
 * provides as a module-level binding. It is read here rather than passed down
 * through props because Server Components have no other way to reach a binding —
 * and it must stay out of anything that crosses to the browser. `INTERNAL_KEY`
 * in particular is read only inside Server Actions and route handlers; it is
 * never rendered, so it never reaches the RSC payload.
 *
 * The cast is the one unavoidable lie in this file: the module's declared type
 * cannot see the config in `cloudflare.config.ts`, so the generated `Env`
 * interface from `.cloudflare/types` is the authority instead. That file is
 * regenerated by `npm run typecheck` (`cf workers types`), so the shape cannot
 * drift from the config without the build noticing.
 */

import { env } from "cloudflare:workers";

export const webEnv = env as unknown as Env;

/** The origin the visitor is actually using, for absolute URLs in the feed. */
export function requestOrigin(request: Request): string {
  return new URL(request.url).origin;
}
